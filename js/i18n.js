export const DICTS = { en, cs };
export const LANGS = { en: "English", cs: "Čeština" };

let lang = "en";

/** "cs" for Czech/Slovak phones, otherwise "en". */
export function detectLang(languages = globalThis.navigator?.languages || [globalThis.navigator?.language || "en"]) {
  return languages.some((l) => /^(cs|sk)\b/i.test(l)) ? "cs" : "en";
}

export function setLang(l) {
  lang = DICTS[l] ? l : "en";
  if (globalThis.document) document.documentElement.lang = lang;
}
export const getLang = () => lang;

/** Plural form index for `n` in the current language. */
function pluralIndex(n, l = lang) {
  if (l === "cs") return n === 1 ? 0 : n >= 2 && n <= 4 ? 1 : 2;
  return n === 1 ? 0 : 1;
}

/** Translate `key`, filling {placeholders} from params. Pass params.n to pick a plural form. */
export function t(key, params = {}) {
  let v = DICTS[lang][key] ?? DICTS.en[key] ?? key;
  if (Array.isArray(v)) v = v[Math.min(v.length - 1, pluralIndex(Math.abs(params.n ?? 0)))];
  return v.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? `{${k}}`));
}

/** Fill static HTML: data-i18n="key" (text) and data-i18n-attr="attr:key;attr:key". */
export function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    for (const pair of el.dataset.i18nAttr.split(";")) {
      const [attr, key] = pair.split(":");
      if (attr && key) el.setAttribute(attr.trim(), t(key.trim()));
    }
  });
}
